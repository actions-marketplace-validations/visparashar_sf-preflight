// Generates src/core/metadataTypes.ts from Salesforce's metadata registry, which ships in the
// @salesforce/source-deploy-retrieve package (Apache-2.0). Only type names, file suffixes and
// folder names are taken; sf-preflight does not depend on that package at run time.
//
//   npm i --no-save @salesforce/source-deploy-retrieve   (in a scratch folder)
//   node scripts/gen-metadata-types.mjs <path to node_modules/@salesforce/source-deploy-retrieve>
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = process.argv[2];
if (!dir) {
  console.error("Usage: node scripts/gen-metadata-types.mjs <path to @salesforce/source-deploy-retrieve>");
  process.exit(1);
}
const pkg = JSON.parse(readFileSync(path.join(dir, "package.json"), "utf8"));
const registry = JSON.parse(readFileSync(path.join(dir, "lib/src/registry/metadataRegistry.json"), "utf8"));

// The registry's suffix index leaves out a few types (StaticResource, Document), so read the types too.
const suffixes = { ...registry.suffixes };
for (const t of Object.values(registry.types)) if (t.suffix && !(t.suffix in suffixes)) suffixes[t.suffix] = t.id;
const bySuffix = {};
for (const [suffix, id] of Object.entries(suffixes)) {
  const t = registry.types[id];
  if (t) bySuffix[suffix] = t.name;
}
// The folder each suffix lives in, for files without a -meta.xml companion (pages/Foo.page).
const dirBySuffix = {};
for (const [suffix, id] of Object.entries(suffixes)) {
  const t = registry.types[id];
  if (t?.directoryName) dirBySuffix[suffix] = t.directoryName;
}
// Types whose folder name identifies them (bundles and content such as lwc/, aura/, staticresources/).
const byDir = {};
for (const t of Object.values(registry.types)) {
  if (t.strictDirectoryName && t.directoryName) byDir[t.directoryName] = t.name;
}
// Types that live in a user-made folder under their directory (reports/<folder>/x.report-meta.xml).
const inFolder = Object.values(registry.types)
  .filter((t) => t.inFolder && t.directoryName)
  .map((t) => t.directoryName)
  .sort();

const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
const body = `// SPDX-License-Identifier: Apache-2.0
// GENERATED by scripts/gen-metadata-types.mjs from @salesforce/source-deploy-retrieve ${pkg.version}
// (Apache-2.0, https://github.com/forcedotcom/source-deploy-retrieve). Do not edit by hand.

/** File suffix (\`Foo.<suffix>-meta.xml\` or \`Foo.<suffix>\`) to metadata type name. */
export const METADATA_BY_SUFFIX: Readonly<Record<string, string>> = ${JSON.stringify(sorted(bySuffix), null, 2)};

/** Suffix to the folder it lives in. */
export const METADATA_DIR_BY_SUFFIX: Readonly<Record<string, string>> = ${JSON.stringify(sorted(dirBySuffix), null, 2)};

/** Folder whose name identifies a bundle or content type (\`lwc/\`, \`aura/\`, \`staticresources/\`, ...). */
export const METADATA_BY_DIR: Readonly<Record<string, string>> = ${JSON.stringify(sorted(byDir), null, 2)};

/** Folders that hold user-created sub-folders (reports, dashboards, documents, email templates). */
export const METADATA_FOLDERED: ReadonlySet<string> = new Set(${JSON.stringify(inFolder)});
`;
writeFileSync(new URL("../src/core/metadataTypes.ts", import.meta.url), body);
console.log(
  `Wrote ${Object.keys(bySuffix).length} suffixes, ${Object.keys(byDir).length} folders from SDR ${pkg.version}.`,
);
